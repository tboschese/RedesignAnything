//! Generate a CycloneDX-ish SBOM + human notices from `cargo metadata` (no extra install).
//! Full HTML licence bundle still uses `cargo about` when installed (see docs/licences.md).

use serde_json::{Value, json};
use std::collections::BTreeMap;
use std::fs;
use std::path::Path;
use std::process::Command;

pub fn generate(root: &Path) -> bool {
    let out = Command::new("cargo")
        .args(["metadata", "--format-version", "1", "--locked"])
        .current_dir(root)
        .output();
    let out = match out {
        Ok(o) if o.status.success() => o,
        Ok(o) => {
            eprintln!(
                "sbom: cargo metadata failed: {}",
                String::from_utf8_lossy(&o.stderr)
            );
            return false;
        }
        Err(e) => {
            eprintln!("sbom: cannot run cargo metadata: {e}");
            return false;
        }
    };
    let meta: Value = match serde_json::from_slice(&out.stdout) {
        Ok(v) => v,
        Err(e) => {
            eprintln!("sbom: bad cargo metadata JSON: {e}");
            return false;
        }
    };
    let packages = meta.get("packages").and_then(|p| p.as_array()).cloned().unwrap_or_default();

    let mut components = Vec::new();
    let mut by_license: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for p in &packages {
        let name = p.get("name").and_then(|v| v.as_str()).unwrap_or("?");
        let version = p.get("version").and_then(|v| v.as_str()).unwrap_or("?");
        let license = p
            .get("license")
            .and_then(|v| v.as_str())
            .unwrap_or("UNKNOWN")
            .to_string();
        let purl = format!("pkg:cargo/{name}@{version}");
        components.push(json!({
            "type": "library",
            "name": name,
            "version": version,
            "purl": purl,
            "licenses": [{ "expression": license }],
        }));
        by_license
            .entry(license)
            .or_default()
            .push(format!("{name}@{version}"));
    }
    components.sort_by(|a, b| {
        let an = a.get("name").and_then(|v| v.as_str()).unwrap_or("");
        let bn = b.get("name").and_then(|v| v.as_str()).unwrap_or("");
        an.cmp(bn).then_with(|| {
            let av = a.get("version").and_then(|v| v.as_str()).unwrap_or("");
            let bv = b.get("version").and_then(|v| v.as_str()).unwrap_or("");
            av.cmp(bv)
        })
    });

    let bom = json!({
        "bomFormat": "CycloneDX",
        "specVersion": "1.5",
        "version": 1,
        "metadata": {
            "tools": [{ "name": "cargo-xtask-sbom", "version": "0.1.0" }],
            "component": {
                "type": "application",
                "name": "redesign-anything",
                "version": env!("CARGO_PKG_VERSION"),
            },
            "notes": [
                "Generated from cargo metadata. Not a substitute for cargo-about HTML notices.",
                "Run `cargo about generate about.hbs -o THIRD-PARTY-LICENSES.html` for full texts when releasing."
            ]
        },
        "components": components,
    });

    let sbom_dir = root.join("docs/sbom");
    if let Err(e) = fs::create_dir_all(&sbom_dir) {
        eprintln!("sbom: mkdir {}: {e}", sbom_dir.display());
        return false;
    }
    let bom_path = sbom_dir.join("cargo-cyclonedx.json");
    let pretty = match serde_json::to_vec_pretty(&bom) {
        Ok(b) => b,
        Err(e) => {
            eprintln!("sbom: serialize: {e}");
            return false;
        }
    };
    if let Err(e) = fs::write(&bom_path, pretty) {
        eprintln!("sbom: write {}: {e}", bom_path.display());
        return false;
    }

    let mut notices = String::from(
        "# Third-party notices (crate inventory)\n\n\
         Generated by `cargo xtask sbom` from `cargo metadata`.\n\n\
         - Full licence **texts**: install `cargo-about` and run \
         `cargo about generate about.hbs -o THIRD-PARTY-LICENSES.html` (see `docs/licences.md`).\n\
         - Machine-readable SBOM: [`docs/sbom/cargo-cyclonedx.json`](sbom/cargo-cyclonedx.json).\n\
         - Bundled assets (fonts, icons): [`ATTRIBUTION.md`](ATTRIBUTION.md).\n\
         - Craft Anything upstream credit: MIT OR Apache-2.0 — see `NOTICE`.\n\n\
         This inventory lists crate names, versions and declared licence expressions. \
         It does **not** redistribute private design systems or customer data.\n\n\
         ## By licence expression\n\n",
    );
    for (lic, crates) in &by_license {
        notices.push_str(&format!("### {lic}\n\n"));
        for c in crates {
            notices.push_str(&format!("- `{c}`\n"));
        }
        notices.push('\n');
    }
    let notices_path = root.join("THIRD_PARTY_NOTICES.md");
    if let Err(e) = fs::write(&notices_path, notices) {
        eprintln!("sbom: write {}: {e}", notices_path.display());
        return false;
    }

    println!(
        "sbom: wrote {} components → {} and {}",
        bom.get("components").and_then(|c| c.as_array()).map(|a| a.len()).unwrap_or(0),
        bom_path.display(),
        notices_path.display()
    );
    true
}
